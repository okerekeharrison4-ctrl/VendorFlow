import React, { useState } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import { X, Sparkles, Check, Crown, Zap, ShieldCheck } from 'lucide-react';
import { useStore } from '../store/StoreContext';
import { formatCurrency } from '../utils/helpers';

interface SubscriptionModalProps {
  isOpen: boolean;
  onClose: () => void;
}

const PRICING_MAP: Record<string, { weekly: number; monthly: number }> = {
  USD: { weekly: 0.99, monthly: 2.99 },
  NGN: { weekly: 500, monthly: 1500 },
  INR: { weekly: 49, monthly: 149 },
  KES: { weekly: 99, monthly: 299 },
  GHS: { weekly: 10, monthly: 30 },
  ZAR: { weekly: 15, monthly: 45 },
  IDR: { weekly: 10000, monthly: 30000 },
  THB: { weekly: 29, monthly: 89 },
  VND: { weekly: 19000, monthly: 59000 },
  PHP: { weekly: 49, monthly: 149 },
  MYR: { weekly: 3.99, monthly: 11.99 },
  KRW: { weekly: 990, monthly: 2900 },
  EGP: { weekly: 25, monthly: 75 },
  TZS: { weekly: 1500, monthly: 4500 },
  CNY: { weekly: 5, monthly: 15 },
};

export const SubscriptionModal: React.FC<SubscriptionModalProps> = ({ isOpen, onClose }) => {
  const { currency, setIsPremium } = useStore();
  const [selectedPlan, setSelectedPlan] = useState<'weekly' | 'monthly'>('monthly');
  const [isProcessing, setIsProcessing] = useState(false);

  if (!isOpen) return null;

  const pricing = PRICING_MAP[currency.code] || PRICING_MAP['USD'];

  const handleSubscribe = () => {
    setIsProcessing(true);
    // Simulate payment gateway integration
    setTimeout(() => {
      setIsPremium(true);
      setIsProcessing(false);
      onClose();
      alert('Successfully upgraded to Premium! 🎉');
    }, 1500);
  };

  const features = [
    'Remove "Generated by VendorFlow" watermark',
    'Upload your custom brand logo',
    'Access exclusive designer templates',
    'Ad-free experience',
    'Priority customer support',
  ];

  return (
    <AnimatePresence>
      {isOpen && (
        <div className="fixed inset-0 z-[200] flex items-center justify-center p-4 sm:p-6">
          <motion.div 
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            className="absolute inset-0 bg-black/60 backdrop-blur-sm"
            onClick={onClose}
          />
          
          <motion.div 
            initial={{ opacity: 0, scale: 0.95, y: 20 }}
            animate={{ opacity: 1, scale: 1, y: 0 }}
            exit={{ opacity: 0, scale: 0.95, y: 20 }}
            className="relative w-full max-w-md bg-surface-container-lowest rounded-[2rem] shadow-2xl overflow-hidden flex flex-col max-h-[90vh]"
          >
            {/* Header */}
            <div className="relative pt-8 pb-6 px-6 text-center bg-gradient-to-b from-primary/10 to-transparent">
              <button 
                onClick={onClose}
                className="absolute top-4 right-4 p-2 bg-surface-container-low rounded-full hover:bg-surface-high transition-colors text-on-surface-variant"
              >
                <X size={20} />
              </button>
              
              <div className="w-16 h-16 mx-auto bg-primary text-on-primary rounded-2xl flex items-center justify-center shadow-lg shadow-primary/30 mb-4 rotate-3">
                <Crown size={32} strokeWidth={2.5} />
              </div>
              
              <h2 className="text-2xl font-black text-on-surface mb-2">Upgrade to Premium</h2>
              <p className="text-sm text-on-surface-variant font-medium px-4">
                Unlock professional tools to grow your business and impress your clients.
              </p>
            </div>

            {/* Features */}
            <div className="px-6 py-2 overflow-y-auto hide-scrollbar">
              <div className="space-y-3 mb-6">
                {features.map((feature, i) => (
                  <div key={i} className="flex items-start gap-3">
                    <div className="mt-0.5 w-5 h-5 rounded-full bg-primary/10 text-primary flex items-center justify-center shrink-0">
                      <Check size={12} strokeWidth={3} />
                    </div>
                    <span className="text-sm font-medium text-on-surface">{feature}</span>
                  </div>
                ))}
              </div>

              {/* Pricing Toggle */}
              <div className="grid grid-cols-2 gap-3 mb-6">
                <button
                  onClick={() => setSelectedPlan('weekly')}
                  className={`relative p-4 rounded-2xl border-2 text-left transition-all ${
                    selectedPlan === 'weekly' 
                      ? 'border-primary bg-primary/5' 
                      : 'border-surface-container-high bg-surface-container-lowest hover:border-primary/30'
                  }`}
                >
                  <div className="text-xs font-bold uppercase tracking-widest text-on-surface-variant mb-1">Weekly</div>
                  <div className="text-xl font-black text-on-surface">
                    {formatCurrency(pricing.weekly, currency.symbol)}
                  </div>
                  {selectedPlan === 'weekly' && (
                    <div className="absolute top-3 right-3 text-primary">
                      <Check size={18} strokeWidth={3} />
                    </div>
                  )}
                </button>

                <button
                  onClick={() => setSelectedPlan('monthly')}
                  className={`relative p-4 rounded-2xl border-2 text-left transition-all ${
                    selectedPlan === 'monthly' 
                      ? 'border-primary bg-primary/5' 
                      : 'border-surface-container-high bg-surface-container-lowest hover:border-primary/30'
                  }`}
                >
                  <div className="absolute -top-3 left-1/2 -translate-x-1/2 bg-primary text-on-primary text-[10px] font-bold uppercase tracking-widest px-3 py-1 rounded-full whitespace-nowrap shadow-sm">
                    Save 25%
                  </div>
                  <div className="text-xs font-bold uppercase tracking-widest text-on-surface-variant mb-1">Monthly</div>
                  <div className="text-xl font-black text-on-surface">
                    {formatCurrency(pricing.monthly, currency.symbol)}
                  </div>
                  {selectedPlan === 'monthly' && (
                    <div className="absolute top-3 right-3 text-primary">
                      <Check size={18} strokeWidth={3} />
                    </div>
                  )}
                </button>
              </div>
            </div>

            {/* Footer / CTA */}
            <div className="p-6 pt-2 bg-surface-container-lowest mt-auto">
              <button 
                onClick={handleSubscribe}
                disabled={isProcessing}
                className="w-full py-4 bg-gradient-to-r from-primary to-primary-heavy text-on-primary rounded-full font-bold text-sm flex items-center justify-center gap-2 shadow-ambient active:scale-[0.98] transition-all disabled:opacity-70 hover:opacity-90"
              >
                {isProcessing ? (
                  <div className="w-5 h-5 border-2 border-on-primary border-t-transparent rounded-full animate-spin" />
                ) : (
                  <>
                    <Sparkles size={18} />
                    Subscribe {selectedPlan === 'weekly' ? 'Weekly' : 'Monthly'}
                  </>
                )}
              </button>
              <p className="text-[10px] text-center text-on-surface-variant mt-4 font-medium px-4">
                Recurring billing. Cancel anytime. By subscribing, you agree to our Terms of Service and Privacy Policy.
              </p>
            </div>
          </motion.div>
        </div>
      )}
    </AnimatePresence>
  );
};
