import React from 'react';
import { Invoice, TemplateConfig } from '../types';
import { formatCurrency } from '../utils/helpers';

interface TemplateRendererProps {
  invoice: Invoice;
  templateConfig: TemplateConfig;
  total: number;
  currencySymbol: string;
  isPremium?: boolean;
  logoUrl?: string;
  isPaid?: boolean;
  removeWatermark?: boolean;
}

export const TemplateRenderer: React.FC<TemplateRendererProps> = ({ 
  invoice, 
  templateConfig, 
  total, 
  currencySymbol,
  isPremium,
  logoUrl,
  isPaid,
  removeWatermark
}) => {
  const style = templateConfig.style || 'modern';
  const props = { invoice, total, currencySymbol, isPremium, logoUrl, isPaid, removeWatermark };

  switch (style) {
    case 'bold':
      return <BoldTemplate {...props} />;
    case 'elegant':
      return <ElegantTemplate {...props} />;
    case 'corporate':
      return <CorporateTemplate {...props} />;
    case 'classic':
      return <ClassicTemplate {...props} />;
    case 'minimal':
      return <MinimalTemplate {...props} />;
    default:
      return <ModernTemplate {...props} />;
  }
};

const ClassicTemplate = ({ invoice, total, currencySymbol, isPremium, logoUrl, isPaid, removeWatermark }: any) => (
  <div className="p-8 bg-white text-gray-900 font-serif border-4 border-double border-gray-300">
    {isPremium && logoUrl && (
      <div className="mb-6 flex justify-center">
        <img src={logoUrl} alt="Logo" className="w-24 h-24 object-contain" referrerPolicy="no-referrer" />
      </div>
    )}
    <div className="text-center mb-8 border-b-2 border-gray-800 pb-4">
      <h1 className="text-3xl font-bold uppercase tracking-widest">{invoice.brandName}</h1>
      <p className="text-sm text-gray-600 mt-2">INVOICE NO. {invoice.invoiceNumber}</p>
    </div>
    <div className="mb-8">
      <p className="font-bold uppercase text-sm mb-2">Bill To:</p>
      <p className="text-lg">{invoice.customerName}</p>
    </div>
    <table className="w-full mb-8">
      <thead className="border-b border-gray-400">
        <tr className="text-left">
          <th className="py-2 font-bold uppercase text-sm">Item</th>
          <th className="py-2 font-bold uppercase text-sm text-center">Qty</th>
          <th className="py-2 font-bold uppercase text-sm text-right">Amount</th>
        </tr>
      </thead>
      <tbody>
        {invoice.items.map((item: any) => (
          <tr key={item.id} className="border-b border-gray-200">
            <td className="py-3">{item.name}</td>
            <td className="py-3 text-center">{item.quantity}</td>
            <td className="py-3 text-right">{formatCurrency(item.price * item.quantity, currencySymbol)}</td>
          </tr>
        ))}
      </tbody>
    </table>
    <div className="flex justify-end border-t-2 border-gray-800 pt-4">
      <div className="text-right">
        <p className="font-bold uppercase text-sm mr-4 inline-block">Total Due:</p>
        <p className="text-2xl font-bold inline-block">{formatCurrency(total, currencySymbol)}</p>
      </div>
    </div>
    {!removeWatermark && (
      <div className="text-center text-gray-400 text-xs mt-12 italic">
        Generated by VendorFlow
      </div>
    )}
  </div>
);

